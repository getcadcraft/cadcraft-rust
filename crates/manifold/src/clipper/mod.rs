//! The parts of Clipper2 that Manifold's `CrossSection` uses (clipper.core.h, clipper.h's `BooleanOp` / `Union` on
//! `PathsD`, clipper.engine.cpp's Vatti clipper with `ClipperD`), as compiled into the manifold-3d 3.5.4 wasm build:
//! no `USINGZ`, no `CLIPPER2_HI_PRECISION`, 32-bit `uintptr_t` (the 64-bit products of `CrossProductSign` /
//! `ProductsAreEqual` are exact either way; i128 here), C++ exceptions on (a range error throws: [`ClipError`]).
//!
//! Not ported: open paths' output, polytrees (owner nesting, splits), offsets, rect clipping, Minkowski,
//! triangulation.
#![allow(clippy::arithmetic_side_effects, clippy::cast_possible_truncation, clippy::cast_sign_loss, clippy::cast_possible_wrap)]

pub(crate) mod engine;
pub(crate) mod sort;

/// `Point64`.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub(crate) struct P64 {
    pub x: i64,
    pub y: i64,
}

/// `PointD`.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub(crate) struct PD {
    pub x: f64,
    pub y: f64,
}

pub(crate) type Path64 = Vec<P64>;
pub(crate) type PathD = Vec<PD>;

/// `FillRule`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FillRule {
    EvenOdd,
    NonZero,
    Positive,
    Negative,
}

/// `ClipType`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum ClipType {
    NoClip,
    Intersection,
    Union,
    Difference,
    Xor,
}

/// Why Clipper2 refused (its exceptions, which manifold-3d passes to JavaScript as a thrown error).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ClipError {
    /// `range_error`: a coordinate times the scale lies outside ±(2^63 − 1) / 4.
    Range,
    /// The clipper's own structures were inconsistent (only on hostile input; the C++ would read out of bounds).
    Internal,
    /// More points than [`crate::cross_section::MAX_CS_POINTS`] (this port's cap).
    TooLarge,
}

impl From<crate::util::Fault> for ClipError {
    fn from(_: crate::util::Fault) -> Self {
        ClipError::Internal
    }
}

pub(crate) const MAX_COORD: i64 = i64::MAX >> 2;
pub(crate) const MIN_COORD: i64 = -MAX_COORD;
pub(crate) const MAX_COORD_F: f64 = MAX_COORD as f64;
pub(crate) const MIN_COORD_F: f64 = MIN_COORD as f64;

/// `static_cast<int64_t>(std::round(v))` as the wasm executes it (non-trapping conversion: NaN → 0, saturating).
#[inline]
pub(crate) fn round_i64(v: f64) -> i64 {
    v.round() as i64
}

/// `static_cast<int64_t>(nearbyint(v))` (round half to even in the default rounding mode).
#[inline]
pub(crate) fn nearbyint_i64(v: f64) -> i64 {
    round_even(v) as i64
}

/// Round half to even, exact (the 2^52 trick: below 2^52 adding and taking away 2^52 rounds to an integer in the
/// default rounding mode; from 2^52 on every double is an integer). Same result as `f64::round_ties_even`, which
/// calls libm's `rint` on baseline x86-64 (no SSE4.1) and showed up in profiles.
#[inline]
pub(crate) fn round_even(v: f64) -> f64 {
    const TWO52: f64 = 4_503_599_627_370_496.0;
    let a = v.abs();
    if a < TWO52 { ((a + TWO52) - TWO52).copysign(v) } else { v }
}

/// `CrossProductSign` (exact).
#[inline]
pub(crate) fn cross_product_sign(p1: P64, p2: P64, p3: P64) -> i32 {
    let a = i128::from(p2.x) - i128::from(p1.x);
    let b = i128::from(p3.y) - i128::from(p2.y);
    let c = i128::from(p2.y) - i128::from(p1.y);
    let d = i128::from(p3.x) - i128::from(p2.x);
    // |a|, |b|, |c|, |d| < 2^64: the products fit in i128 when the inputs are in Clipper's range (2^62); saturate beyond
    let ab = a.saturating_mul(b);
    let cd = c.saturating_mul(d);
    match ab.cmp(&cd) {
        core::cmp::Ordering::Greater => 1,
        core::cmp::Ordering::Less => -1,
        core::cmp::Ordering::Equal => 0,
    }
}

/// `IsCollinear` (`ProductsAreEqual`, exact).
#[inline]
pub(crate) fn is_collinear(pt1: P64, shared: P64, pt2: P64) -> bool {
    let a = i128::from(shared.x.wrapping_sub(pt1.x));
    let b = i128::from(pt2.y.wrapping_sub(shared.y));
    let c = i128::from(shared.y.wrapping_sub(pt1.y));
    let d = i128::from(pt2.x.wrapping_sub(shared.x));
    a.saturating_mul(b) == c.saturating_mul(d)
}

/// `DotProduct(pt1, pt2, pt3)`.
#[inline]
pub(crate) fn dot_product(p1: P64, p2: P64, p3: P64) -> f64 {
    (p2.x.wrapping_sub(p1.x)) as f64 * (p3.x.wrapping_sub(p2.x)) as f64
        + (p2.y.wrapping_sub(p1.y)) as f64 * (p3.y.wrapping_sub(p2.y)) as f64
}

/// `PerpendicDistFromLineSqrd`.
#[inline]
pub(crate) fn perpendic_dist_from_line_sqrd(pt: P64, line1: P64, line2: P64) -> f64 {
    let a = (pt.x.wrapping_sub(line1.x)) as f64;
    let b = (pt.y.wrapping_sub(line1.y)) as f64;
    let c = (line2.x.wrapping_sub(line1.x)) as f64;
    let d = (line2.y.wrapping_sub(line1.y)) as f64;
    if c == 0.0 && d == 0.0 {
        return 0.0;
    }
    let e = a * d - c * b;
    (e * e) / (c * c + d * d)
}

/// `GetLineIntersectPt` (the default, not hi-precision, variant): `None` for parallel lines.
pub(crate) fn get_line_intersect_pt(ln1a: P64, ln1b: P64, ln2a: P64, ln2b: P64) -> Option<P64> {
    let dx1 = (ln1b.x.wrapping_sub(ln1a.x)) as f64;
    let dy1 = (ln1b.y.wrapping_sub(ln1a.y)) as f64;
    let dx2 = (ln2b.x.wrapping_sub(ln2a.x)) as f64;
    let dy2 = (ln2b.y.wrapping_sub(ln2a.y)) as f64;
    let det = dy1 * dx2 - dy2 * dx1;
    if det == 0.0 {
        return None;
    }
    let t = ((ln1a.x.wrapping_sub(ln2a.x)) as f64 * dy2 - (ln1a.y.wrapping_sub(ln2a.y)) as f64 * dx2) / det;
    if t <= 0.0 {
        Some(ln1a)
    } else if t >= 1.0 {
        Some(ln1b)
    } else {
        // static_cast<int64_t>(double): truncation
        Some(P64 { x: (ln1a.x as f64 + t * dx1) as i64, y: (ln1a.y as f64 + t * dy1) as i64 })
    }
}

/// `SegmentsIntersect(seg1a, seg1b, seg2a, seg2b, inclusive = false)`.
pub(crate) fn segments_intersect(seg1a: P64, seg1b: P64, seg2a: P64, seg2b: P64) -> bool {
    let dy1 = (seg1b.y.wrapping_sub(seg1a.y)) as f64;
    let dx1 = (seg1b.x.wrapping_sub(seg1a.x)) as f64;
    let dy2 = (seg2b.y.wrapping_sub(seg2a.y)) as f64;
    let dx2 = (seg2b.x.wrapping_sub(seg2a.x)) as f64;
    let cp = dy1 * dx2 - dy2 * dx1;
    if cp == 0.0 {
        return false;
    }
    let ax = (seg1a.x.wrapping_sub(seg2a.x)) as f64;
    let ay = (seg1a.y.wrapping_sub(seg2a.y)) as f64;
    let mut t = ax * dy2 - ay * dx2;
    if t == 0.0 {
        return false;
    }
    if t > 0.0 {
        if cp < 0.0 || t >= cp {
            return false;
        }
    } else if cp > 0.0 || t <= cp {
        return false;
    }
    t = ax * dy1 - ay * dx1;
    if t == 0.0 {
        return false;
    }
    if t > 0.0 { cp > 0.0 && t < cp } else { cp < 0.0 && t > cp }
}

/// `GetClosestPointOnSegment` for `Point64`.
pub(crate) fn get_closest_point_on_segment(off: P64, seg1: P64, seg2: P64) -> P64 {
    if seg1.x == seg2.x && seg1.y == seg2.y {
        return seg1;
    }
    let dx = (seg2.x.wrapping_sub(seg1.x)) as f64;
    let dy = (seg2.y.wrapping_sub(seg1.y)) as f64;
    let mut q = ((off.x.wrapping_sub(seg1.x)) as f64 * dx + (off.y.wrapping_sub(seg1.y)) as f64 * dy) / (dx * dx + dy * dy);
    q = q.clamp(0.0, 1.0);
    P64 { x: seg1.x.wrapping_add(nearbyint_i64(q * dx)), y: seg1.y.wrapping_add(nearbyint_i64(q * dy)) }
}

/// `Area(const Path<double>&)` (pairs of edges per step, as the C++ unrolls it).
pub(crate) fn area_d(path: &[PD]) -> f64 {
    let cnt = path.len();
    if cnt < 3 {
        return 0.0;
    }
    let mut a = 0.0;
    let mut it2 = cnt - 1;
    let stop = if cnt & 1 == 0 { it2 + 1 } else { it2 };
    let mut it1 = 0usize;
    let p = |i: usize| path.get(i).copied().unwrap_or_default();
    while it1 != stop {
        a += (p(it2).y + p(it1).y) * (p(it2).x - p(it1).x);
        it2 = it1 + 1;
        a += (p(it1).y + p(it2).y) * (p(it1).x - p(it2).x);
        it1 += 2;
    }
    if cnt & 1 != 0 {
        a += (p(it2).y + p(it1).y) * (p(it2).x - p(it1).x);
    }
    a * 0.5
}

/// `ScalePaths<int64_t, double>(paths, scale, error_code)`: the bounds checked against Clipper's range first.
pub(crate) fn scale_paths_to_64(paths: &[PathD], scale: f64) -> Result<Vec<Path64>, ClipError> {
    // GetBounds<double, double>
    let (mut xmin, mut ymin, mut xmax, mut ymax) = (f64::MAX, f64::MAX, f64::MIN, f64::MIN);
    for path in paths {
        for p in path {
            if p.x < xmin {
                xmin = p.x;
            }
            if p.x > xmax {
                xmax = p.x;
            }
            if p.y < ymin {
                ymin = p.y;
            }
            if p.y > ymax {
                ymax = p.y;
            }
        }
    }
    if xmin * scale < MIN_COORD_F || xmax * scale > MAX_COORD_F || ymin * scale < MIN_COORD_F || ymax * scale > MAX_COORD_F {
        return Err(ClipError::Range);
    }
    Ok(paths.iter().map(|path| path.iter().map(|p| P64 { x: round_i64(p.x * scale), y: round_i64(p.y * scale) }).collect()).collect())
}

/// `BooleanOp(cliptype, fillrule, subjects, clips, precision)` on `PathsD` (`ClipperD`).
pub(crate) fn boolean_op_d(
    ct: ClipType,
    fr: FillRule,
    subjects: &[PathD],
    clips: &[PathD],
    precision: i32,
) -> Result<Vec<PathD>, ClipError> {
    // CheckPrecisionRange: Manifold always passes 8, inside ±8
    let precision = precision.clamp(-8, 8);
    // scale_ = 2^(ilogb(10^precision) + 1)
    let p10 = 10f64.powi(precision);
    let ilogb = ((p10.to_bits() >> 52) & 0x7ff) as i32 - 1023;
    let scale = 2f64.powi(ilogb + 1);
    let inv_scale = 1.0 / scale;
    let mut c = engine::Clipper::new();
    c.add_paths(&scale_paths_to_64(subjects, scale)?, engine::PathType::Subject)?;
    if !clips.is_empty() {
        c.add_paths(&scale_paths_to_64(clips, scale)?, engine::PathType::Clip)?;
    }
    Ok(c.execute_d(ct, fr, inv_scale)?)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn area_matches_shoelace() {
        let sq = vec![PD { x: 0.0, y: 0.0 }, PD { x: 1.0, y: 0.0 }, PD { x: 1.0, y: 1.0 }, PD { x: 0.0, y: 1.0 }];
        assert_eq!(area_d(&sq), 1.0);
        let tri = vec![PD { x: 0.0, y: 0.0 }, PD { x: 2.0, y: 0.0 }, PD { x: 0.0, y: 1.0 }];
        assert_eq!(area_d(&tri), 1.0);
    }

    #[test]
    fn scale_and_range() {
        let p = vec![vec![PD { x: 0.5, y: -0.5 }, PD { x: f64::NAN, y: 1.0 }]];
        let s = scale_paths_to_64(&p, 2.0).unwrap();
        // round half away from zero; NaN → 0 (the wasm's saturating conversion)
        assert_eq!(s[0][0], P64 { x: 1, y: -1 });
        assert_eq!(s[0][1].x, 0);
        assert_eq!(scale_paths_to_64(&[vec![PD { x: 1e12, y: 0.0 }]], 134_217_728.0), Err(ClipError::Range));
        assert_eq!(scale_paths_to_64(&[vec![PD { x: f64::INFINITY, y: 0.0 }]], 2.0), Err(ClipError::Range));
    }

    #[test]
    fn round_even_matches_std() {
        let mut x = -10.0f64;
        while x < 10.0 {
            assert_eq!(round_even(x).to_bits(), x.round_ties_even().to_bits(), "{x}");
            x += 0.125;
        }
        for x in [0.5, 1.5, 2.5, -0.5, -2.5, 4_503_599_627_370_495.5, 1e300, -1e-300, -0.0, f64::INFINITY, 0.49999999999999994] {
            assert_eq!(round_even(x).to_bits(), x.round_ties_even().to_bits(), "{x}");
        }
        assert!(round_even(f64::NAN).is_nan());
    }

    #[test]
    fn cross_sign_exact() {
        let a = P64 { x: 0, y: 0 };
        let b = P64 { x: 1 << 61, y: 1 << 61 };
        let c = P64 { x: (1 << 61) + 1, y: (1 << 61) + 1 };
        assert_eq!(cross_product_sign(a, b, c), 0);
        assert!(is_collinear(a, b, c));
    }
}
