fn read_one(r: &mut BitReader, hr: Option<&mut BitReader>, t: T) -> Res<V> {
    Ok(match t {
        T::B => V::from(r.b()?),
        T::Bs => V::from(r.bs()?),
        T::Bl => V::from(r.bl()?),
        T::Bll => V::Num(r.bll()?),
        T::Bd => V::Num(r.bd()?),
        T::Rc => V::from(r.rc()?),
        T::Tv => V::Str(r.tv()?),
        T::T => V::Str(r.t()?),
        T::H => V::Str(handle_hex(match hr {
            Some(h) => h.h(0.0)?,
            None => r.h(0.0)?,
        })),
        T::Hs => V::Str(handle_hex(r.h(0.0)?)),
        T::Cmc => V::Obj(r.cmc()?),
        T::Bd3 => r.bd3()?,
        T::Rd2 => r.rd2()?,
        T::Td | T::Ts => {
            let d = r.bl()?;
            let ms = r.bl()?;
            V::Num(f64::from(d) + f64::from(ms) / 86_400_000.0)
        }
    })
}

/// Read every variable of `ver`. `handles` = the handle stream (R2007+). Returns (vars, error text).
pub fn decode_header_vars(r: &mut BitReader, ver: u32, mut handles: Option<&mut BitReader>) -> (Obj, Option<String>) {
    let mut vars = Obj::with_capacity(400);
    let mut error = None;
    for &(name, t, from, to) in HEADER_VARS {
        if ver < from || ver > to {
            continue;
        }
        if name == "CPSNID" && vars.num("CEPSNTYPE") != Some(3.0) {
            continue;
        }
        match read_one(r, handles.as_deref_mut(), t) {
            Ok(v) => vars.set(name, v),
            Err(e) => {
                error = Some(e.0);
                break;
            }
        }
    }
    if let Some(f) = vars.num("FLAGS") {
        let f = crate::util::to_i32(f);
        vars.set("CELWEIGHT", f & 0x1F);
        vars.set("ENDCAPS", (f & 0x60) >> 5);
        vars.set("JOINSTYLE", (f & 0x180) >> 7);
        vars.set("LWDISPLAY", if f & 0x200 != 0 { 0 } else { 1 });
        vars.set("XEDIT", if f & 0x400 != 0 { 0 } else { 1 });
        vars.set("EXTNAMES", if f & 0x800 != 0 { 1 } else { 0 });
        vars.set("PSTYLEMODE", if f & 0x2000 != 0 { 1 } else { 0 });
        vars.set("OLESTARTUP", if f & 0x4000 != 0 { 1 } else { 0 });
    }
    (vars, error)
}
